import "../../packages/components/src/styles/index.css";
import { Button, LanguageCombobox, LanguageSelect, ThemeToggle, createLocaleController } from "../../packages/components/src";
import { addPageHideCleanup, runCleanups } from "../../packages/core/src/events";

const app = document.querySelector<HTMLElement>("#app")!;
app.style.cssText = "max-width:60rem;margin:auto;padding:1rem;font:16px/1.5 sans-serif;display:grid;gap:1rem";
const title = document.createElement("h1"); title.textContent = "AF Language Picker Audit";
const status = document.createElement("p"); status.setAttribute("role", "status");
const report = document.createElement("ol");
const locale = createLocaleController<"en" | "ru" | "ar">({ supportedLocales: ["en", "ru", "ar"], fallbackLocale: "en", initialLocale: "en", storage: null, navigatorSource: null });
let changes = 0;
const changed = () => { changes += 1; status.textContent = `User change ${changes}: ${locale.getLocale()}`; };
const native = LanguageSelect({ locale, label: "Native language picker", nameFormat: "localized-and-native", onLocaleChange: changed });
const combo = LanguageCombobox({ locale, label: "Confirmed language picker", nameFormat: "localized-and-native", onLocaleChange: changed });
const names = LanguageCombobox({ locale, label: "Native names", nameFormat: "native" });
const longLabel = "LongLanguageLabelWithoutSpaces".repeat(6);
const long = LanguageCombobox({ locale, label: "Long language labels", getItemLabel: () => longLabel });
const theme = ThemeToggle({ announcement: false });
const resize = Button({ text: "Update picker width", onPress() { combo.update({ width: "24rem" }); status.textContent = "Picker width updated"; } });
const run = Button({ text: "Run language checks", onPress() {
    const checks: Array<{ name: string; passed: boolean }> = [];
    const check = (name: string, passed: boolean) => checks.push({ name, passed });
    const previous = locale.getLocale(); locale.setLocale("en");
    check("Native picker retains native select semantics", native.control instanceof HTMLSelectElement && Boolean(native.control.labels?.length));
    combo.control.focus();
    check("Confirmed picker is readonly and does not open on focus", combo.control.readOnly && !combo.combobox.isOpen());
    check("Native names retain their own language metadata", names.combobox.getItem("ru")!.option.lang === "ru" && names.combobox.getItem("ar")!.option.lang === "ar");
    const option = combo.combobox.getItem("ru")!.option; const nativeOption = native.select.getItem("ru")!.option; const before = changes;
    locale.setLocale("ru");
    check("External locale synchronizes native and confirmed values", native.select.getValue() === "ru" && combo.combobox.getSelectedValue() === "ru");
    check("Locale changes preserve option nodes and current focus", combo.combobox.getItem("ru")!.option === option && native.select.getItem("ru")!.option === nativeOption && document.activeElement === combo.control);
    check("External locale change does not emit a user callback", changes === before);
    check("Combined names use current UI language metadata", combo.combobox.getItem("en")!.option.lang === "ru");
    check("Controller synchronizes document language", document.documentElement.lang === "ru");
    locale.setLocale("ar");
    check("Controller synchronizes RTL direction", document.documentElement.dir === "rtl");
    locale.setLocale("en");
    combo.combobox.open(); combo.combobox.setActiveValue("ru");
    const pending = combo.combobox.getActiveOption(); combo.update({ className: "updated-picker", width: "20rem" });
    check("Chrome-only update preserves an open pending choice", combo.combobox.isOpen() && combo.combobox.getActiveOption() === pending && locale.getLocale() === "en");
    check("Authored picker label survives unrelated updates", combo.combobox.getLabelElement()?.textContent === "Confirmed language picker");
    combo.combobox.close();
    check("Closing a pending choice does not change the locale", locale.getLocale() === "en");
    long.combobox.open();
    const popup = long.combobox.listbox.getBoundingClientRect();
    check("Long language popup stays within viewport bounds", popup.left >= 0 && popup.right <= innerWidth + 1);
    check("Long language options wrap without horizontal scrolling", long.combobox.listbox.scrollWidth <= long.combobox.listbox.clientWidth + 1);
    long.combobox.close();
    check("Picker control sizes remain within their container", [native, combo, names, long].every(picker => picker.control.getBoundingClientRect().width <= picker.element.clientWidth + 1));
    check("Controls retain minimum touch target height", [native, combo, names, long].every(picker => picker.control.getBoundingClientRect().height >= 44));
    check("Document has no horizontal overflow", document.documentElement.scrollWidth <= innerWidth);
    locale.setLocale(previous);
    report.replaceChildren(...checks.map(check => { const li = document.createElement("li"); li.textContent = `${check.passed ? "PASS" : "FAIL"}: ${check.name}`; return li; }));
    status.textContent = `${checks.filter(check => check.passed).length}/${checks.length} language checks passed`;
} });
app.append(title, run.element, theme.element, status, native.element, combo.element, resize.element, names.element, long.element, report);
addPageHideCleanup(window, () => runCleanups([native.destroy, combo.destroy, names.destroy, long.destroy, theme.destroy, resize.destroy, run.destroy, locale.destroy]));
